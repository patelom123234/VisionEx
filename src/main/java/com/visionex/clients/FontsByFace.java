package com.visionex.clients;

import java.awt.Font;

public class FontsByFace {
    public final Font regular;
    public final Font semiBold;
    public final Font bold;

    public FontsByFace(Font regular, Font semiBold, Font bold) {
        this.regular = regular;
        this.semiBold = semiBold;
        this.bold = bold;
    }
}

